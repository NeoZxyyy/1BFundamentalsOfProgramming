public class EvenNumbers_BufferedReader {
    public static void main(String[] args) {


        int number = 2;


        while (number <=  100){
            System.out.print(number+ " ");
            number+=2;
            if (number == 22 || number == 42 || number == 62 || number == 82){
                System.out.println();

            }


        }
    }
}
